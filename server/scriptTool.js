// Сценарий как структура, а не как текст.
//
// Модель возвращает реплики вызовом инструмента: блок, границы во времени,
// текст. Просить структуру текстом и разбирать её потом регулярными
// выражениями означало бы, что любая вольность в оформлении рушит экран.
//
// Названия блоков не зашиты в код. Их задаёт владелец в Настройках, и схема
// собирается под них на каждый запрос: у одного агентства это Хук и Призыв,
// у другого ЗКТ и В камеру, и спорить с этим из кода бессмысленно.
//
// Блок это роль реплики в ролике, а не план съёмки. Кадров, планов, монтажа
// и хэштегов в выдаче нет: для этого другие экраны.

export const DEFAULT_BLOCKS = ['Хук', 'ЗКТ', 'В камеру', 'Призыв']

export const FORMAT_LABEL = { reels: 'REELS', stories: 'СТОРИС', post: 'ПОСТ' }
export const GOAL_LABEL = { leads: 'ЗАЯВКИ', reach: 'ОХВАТ', trust: 'ДОВЕРИЕ', warmup: 'ПРОГРЕВ' }

const cut = (s, n) => String(s ?? '').slice(0, n)
const clamp = (n, lo, hi) => Math.min(Math.max(n, lo), hi)

/**
 * Список блоков из настроек: по одному в строке. Пустое значение и мусор
 * возвращают к встроенному набору, потому что схема без вариантов не
 * соберётся вовсе, а молча выдать сценарий без структуры хуже.
 */
export function parseBlocks(raw) {
  if (typeof raw !== 'string') return DEFAULT_BLOCKS
  const list = raw
    .split('\n')
    .map(s => s.trim())
    .filter(Boolean)
    .map(s => cut(s, 40))
    .slice(0, 10)
  // Повторы убираем: в схеме это набор допустимых значений, а не порядок.
  // Повторять блок внутри сценария модели никто не запрещает.
  const unique = [...new Set(list)]
  return unique.length >= 2 ? unique : DEFAULT_BLOCKS
}

