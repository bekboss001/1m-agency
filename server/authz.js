// Что можно тому, кто зовёт серверную функцию.
//
// Те же правила, что у базы (db/security.sql): сотрудник — одобренный
// пользователь с ролью не «клиент»; администратор — одобренный с ролью admin.
// Зарегистрироваться может кто угодно, поэтому «вошёл» ещё ничего не значит:
// до одобрения у человека нет никаких прав.
//
// Профиль функции читают под токеном самого человека: RLS отдаёт ему его
// собственную строку всегда, а чужие — только сотрудникам.

export const isAdmin = p => p?.is_approved === true && p.role === 'admin'

export const isStaff = p => p?.is_approved === true && Boolean(p.role) && p.role !== 'client' && p.role !== 'pending'
