-- Правка «выпущено» руками у клиента, которого ведёт сверка.
--
-- «Выпущено» у такого клиента не хранится, а каждый прогон считается заново по
-- ленте Instagram. Записать туда число напрямую нельзя: ближайшая сверка
-- посчитает своё и правку затрёт.
--
-- Поэтому запоминаем не само число, а поправку к нему — разницу между тем, что
-- поставил человек, и тем, что насчиталось. Сверка прибавляет её к своему
-- счёту, поэтому сразу после правки в таблице стоит введённое число, а новые
-- публикации продолжают приходить сверху.
--
-- Поправка живёт до конца периода: при закрытии она уже вошла в перенос, и
-- дальше её незачем помнить — сверка обнуляет её сама.
--
-- Долгу такая колонка не нужна: carry_posts сверка не пересчитывает, пока
-- период не закрылся, и правка в нём держится сама.
--
-- Выполнить один раз в Supabase → SQL Editor.

alter table public.clients
  add column if not exists posts_adjust integer not null default 0;

comment on column public.clients.posts_adjust is
  'Поправка к счёту публикаций, поставленная руками. Сверка прибавляет её к своему счёту и обнуляет при закрытии периода.';

-- Уход клиента в архив обнуляет перенос (db/sync_write.sql): счёт при возврате
-- начинается с нуля. Поправка — часть того же счёта, и переживать паузу она
-- тоже не должна.
create or replace function public.clients_reset_sync_on_archive()
returns trigger
language plpgsql
as $$
-- Всё остальное оставлено как в db/sync_write.sql: «выпущено» и дата последней
-- выкладки при архивации намеренно не стираются.
begin
  if old.is_active and not new.is_active then
    new.carry_posts := null;
    new.period_plan := null;
    new.period_day  := null;
    new.posts_adjust := 0;
  end if;
  return new;
end;
$$;
