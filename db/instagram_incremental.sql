-- Точка отсчёта для кнопки «Подтянуть из Instagram».
--
-- Кнопка перестала пересчитывать окно месяца заново и теперь прибавляет к
-- сохранённому числу только те публикации, что вышли ПОСЛЕ прошлой сверки.
-- Именно поэтому недобор прошлого периода не обнуляется на границе месяца:
-- счётчик не сбрасывается, а продолжает расти.
--
-- Хранить одну лишь дату мало. Если 6 сентября вышло два поста, а сверку
-- сделали между ними, «строго позже 6 сентября» потеряло бы второй.
-- Поэтому запоминаем точный момент последней засчитанной публикации.
--
-- Выполнить один раз в Supabase → SQL Editor.

alter table public.clients
  add column if not exists instagram_synced_at timestamptz;

comment on column public.clients.instagram_synced_at is
  'Время последней публикации, уже учтённой кнопкой «Подтянуть из Instagram». '
  'NULL — сверки ещё не было, кнопка считает по текущему периоду плана.';
