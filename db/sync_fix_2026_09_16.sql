-- Поправка долга после первой сверки 16.09.2026: Бэйби Рум и KTB.
--
-- Первая сверка перевела таблицу клиентов в периоды, и у двух клиентов
-- долг вышел на один пост больше, чем по гугл-таблице агентства:
--   Бэйби Рум: в гугл-таблице 11 из 12 до 03.09, сверка записала долг 4
--              (по таблице выходит 3, осталось 11, а не 12);
--   KTB:       в гугл-таблице 6 из 12 до 24.09, сверка записала долг 7
--              (по таблице выходит 6, осталось 4, а не 5).
-- Расчёт верный, расхождение во входных данных: в приложении «Выпущено» у
-- обоих стояло на один меньше, чем в гугл-таблице на 16.09.
--
-- Сначала посмотрите первый запрос: что было в приложении до сверки. Если там
-- действительно 10 у Бэйби Рум и 5 у KTB, выполните обновление ниже.
--
-- Обновление срабатывает, только пока долг равен записанному сверкой (-4 и -7):
-- повторный запуск ничего не изменит.

select name, published_posts as "выпущено до сверки", last_post_date, contract_end
from public.clients_before_sync
where name in ('Бэйби Рум', 'KTB', 'КТБ', 'КТВ');

update public.clients
set carry_posts = case name when 'Бэйби Рум' then -3 else -6 end
where (name = 'Бэйби Рум' and carry_posts = -4)
   or (name in ('KTB', 'КТБ', 'КТВ') and carry_posts = -7)
returning name, carry_posts as "долг теперь", published_posts;
