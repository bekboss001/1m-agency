-- Структурная часть реплики.
--
-- Уточняющие вопросы модель теперь отдаёт не текстом, а структурой: заголовок
-- и готовые варианты. Приложение рисует по ней кнопки, чтобы отвечать тапом,
-- а не перепечатывать «1а 2б 3в».
--
-- Текст реплики при этом остаётся человекочитаемым и лежит в content: он
-- уходит в историю для модели и показывается там, где кнопки отрисовать
-- нельзя. meta нужна только для отрисовки.
--
-- Выполнить один раз в Supabase → SQL Editor.

alter table public.ai_messages
  add column if not exists meta jsonb;

comment on column public.ai_messages.meta is
  'Структура реплики для интерфейса. Сейчас единственный вид: {"ask":[{"title":…,"options":[…]}]}.';
