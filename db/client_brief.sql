-- Развёрнутый бриф клиента.
--
-- Одного свободного поля оказалось мало: сценарист переспрашивает про цены,
-- географию, возражения и про то, что вообще можно снимать. Эти вопросы
-- повторяются от клиента к клиенту, значит им место в анкете, а не в переписке.
--
-- Один столбец jsonb, а не двенадцать колонок. Набор пунктов брифа будет
-- меняться по ходу работы, и добавлять колонку под каждый новый пункт значило
-- бы миграцию на каждую правку анкеты. Ровно та же причина, по которой
-- app_settings сделана таблицей ключ-значение.
--
-- Свободное поле brief остаётся: часть брифов по графам не раскладывается,
-- и заставлять их раскладываться значит терять то, что не влезло.
--
-- Выполнить один раз в Supabase → SQL Editor.

alter table public.clients
  add column if not exists brief_data jsonb;

comment on column public.clients.brief_data is
  'Анкета клиента для ИИ. Ключи заданы в api/briefFields.js: product, price, geo, usp, audience, pains, tone, lang, stop, shooting, cta, goal.';
