export const BRIEF_KEYS = BRIEF_GROUPS.flatMap(g => g.items.map(([k]) => k))

const LABELS = Object.fromEntries(
  BRIEF_GROUPS.flatMap(g => g.items.map(([k, label]) => [k, label])),
)

// Текст брифа для модели. Пустые поля пропускаются: строка «Цены: не указано»
// не добавляет знания, а место в запросе занимает.
export function renderBrief(data, freeText) {
  if (!data && !freeText) return ''

  const lines = []
  for (const key of BRIEF_KEYS) {
    const v = data?.[key]
    if (typeof v === 'string' && v.trim()) lines.push(LABELS[key] + ': ' + v.trim())
  }
  if (typeof freeText === 'string' && freeText.trim()) {
    lines.push('Прочее: ' + freeText.trim())
  }
  return lines.join('\n')
}
