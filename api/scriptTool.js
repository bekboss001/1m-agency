/* ───────────────────────────── Проверка ответа ───────────────────────── */

const clamp = (n, lo, hi) => Math.min(Math.max(n, lo), hi)
const cut = (s, n) => String(s ?? '').slice(0, n)

/**
 * Схема схемой, но полагаться на неё вслепую нельзя: сломанная структура
 * уронила бы экран у всех, кто откроет этот сценарий.
 *
 * Здесь же чинится то, что модель путает чаще всего: разрывы и наложения
 * таймкодов. Выкидывать из-за них весь сценарий жалко, а показать реплики
 * внахлёст нельзя, поэтому границы пересобираются по порядку.
 */
export function validScript(input, durationSec) {
  const rawTitle = cut(input?.title, 80).trim()
  const raw = Array.isArray(input?.lines) ? input.lines : []

  const lines = raw
    .filter(l => ROLES.includes(l?.role) && typeof l?.text === 'string' && l.text.trim())
    .map(l => ({
      role: l.role,
      from: Number.isFinite(l.from) ? Math.max(0, l.from) : 0,
      to: Number.isFinite(l.to) ? Math.max(0, l.to) : 0,
      text: cut(l.text, 1200).trim(),
      // В gaps держим только те метки, что действительно стоят в тексте:
      // счётчик уточнений должен совпадать с тем, что видно глазами.
      gaps: (Array.isArray(l.gaps) ? l.gaps : [])
        .filter(g => typeof g === 'string' && g.trim())
        .map(g => cut(g, 80).trim())
        .filter(g => l.text.includes('[[' + g + ']]'))
        .slice(0, 4),
    }))
    .slice(0, 12)

  if (lines.length === 0) return null

  // Границы пересобираем от нуля, сохраняя заданные моделью длительности.
  // Так исчезают разрывы и наложения, а пропорции остаются её.
  let cursor = 0
  for (const l of lines) {
    const span = clamp(Math.round(l.to - l.from) || 3, 1, 600)
    l.from = cursor
    l.to = cursor + span
    cursor = l.to
  }

  // Если модель разошлась с заказанным хронометражом, не подгоняем: расхождение
  // видно на экране и подсвечивается. Молчаливая подгонка сделала бы цифру
  // правдоподобной и бесполезной.
  void durationSec

  return { title: rawTitle || 'Сценарий', lines }
}

/* ──────────────────────────── Текст для копии ─────────────────────────── */

const mmss = s => `${Math.floor(s / 60)}:${String(Math.round(s % 60)).padStart(2, '0')}`

// Метки уточнений в копии остаются видимыми, но в одинарных скобках: двойные
// это наш внутренний маркер, человеку он ничего не говорит.
export const plainLine = text => String(text ?? '').replace(/\[\[(.+?)\]\]/g, '[$1]')

export function renderScriptText(title, lines) {
  const head = String(title || 'Сценарий').toUpperCase()
  const body = (lines || []).map(l =>
    `${ROLE_LABEL[l.role] || l.role} · ${mmss(l.from)}–${mmss(l.to)}\n${plainLine(l.text)}`,
  )
  return [head, '', ...body].join('\n\n')
}
