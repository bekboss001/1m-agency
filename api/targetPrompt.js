const money = n => '$' + (Math.round((n || 0) * 100) / 100).toLocaleString('ru-RU')
const num = n => Math.round(n || 0).toLocaleString('ru-RU')
const cut = (s, n) => String(s ?? '').slice(0, n)

function renderRow(r, withCampaigns) {
  const out = [
    `${cut(r.name, 80)}: потрачено ${money(r.spend)}, охват ${num(r.reach)}, ` +
    `кликов ${num(r.clicks)}, CTR ${(r.ctr || 0).toFixed(2)}%, ` +
    `переписок ${num(r.messaging)}` +
    (r.cpm ? `, цена переписки ${money(r.cpm)}` : ', переписок нет'),
  ]

  if (withCampaigns && Array.isArray(r.campaigns) && r.campaigns.length) {
    out.push('  Кампании:')
    for (const c of r.campaigns.slice(0, 15)) {
      out.push(
        `  ${cut(c.name, 80)}: ${money(c.spend)}, охват ${num(c.reach)}, ` +
        `CTR ${(c.ctr || 0).toFixed(2)}%, переписок ${num(c.messaging)}` +
        (c.cpm ? `, по ${money(c.cpm)}` : ''),
      )
    }
  }
  return out.join('\n')
}

// Ряд дневных расходов моделью читается плохо: сорок чисел она пересказывает,
// а не осмысливает. Отдаём готовое сравнение половин периода.
function renderTrend(series) {
  if (!Array.isArray(series) || series.length < 4) return ''
  const half = Math.floor(series.length / 2)
  const a = series.slice(0, half).reduce((s, v) => s + (v || 0), 0)
  const b = series.slice(half).reduce((s, v) => s + (v || 0), 0)
  if (a <= 0) return ''
  const pct = Math.round(((b - a) / a) * 100)
  return `\nРасход по дням: первая половина периода ${money(a)}, вторая ${money(b)}, ` +
    `${pct >= 0 ? 'рост' : 'снижение'} на ${Math.abs(pct)}%. Это только деньги, не результат.`
}

export function renderTargetData({ period, scope, rows, series }) {
  const list = (Array.isArray(rows) ? rows : []).slice(0, 20)
  const single = list.length === 1

  const total = list.reduce((a, r) => ({
    spend: a.spend + (r.spend || 0),
    messaging: a.messaging + (r.messaging || 0),
    reach: a.reach + (r.reach || 0),
  }), { spend: 0, messaging: 0, reach: 0 })

  const head = [
    `Период: ${cut(period, 60)}.`,
    `Срез: ${single ? cut(scope, 80) : `все кабинеты, ${list.length} шт.`}`,
    `Итого: потрачено ${money(total.spend)}, охват ${num(total.reach)}, ` +
    `переписок ${num(total.messaging)}` +
    (total.messaging > 0 ? `, средняя цена переписки ${money(total.spend / total.messaging)}` : ''),
  ]

  const body = list.map(r => renderRow(r, single)).join('\n')

  return head.join('\n') + '\n\n' + body + renderTrend(series)
}
